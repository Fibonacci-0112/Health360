#!/usr/bin/env node
/**
 * Copies packages/domain and packages/schemas into supabase/functions/_shared/generated so Edge
 * Functions run the exact same math and validation as the app (PLAN.md §2.2). Deploys only ship the
 * supabase/functions directory, so the functions can't import the workspace packages directly.
 *
 *   node tools/codegen/copy-shared.mjs          write the copy
 *   node tools/codegen/copy-shared.mjs --check  exit 1 if the copy is stale (CI)
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'supabase/functions/_shared/generated');
const sources = [
  { name: 'domain', dir: join(root, 'packages/domain/src') },
  { name: 'schemas', dir: join(root, 'packages/schemas/src') },
];
// Workspace imports become relative paths inside the generated tree. Bare npm imports (zod) stay
// as they are and resolve through each function's deno.json.
const rewrites = { '@health360/domain': '../domain/index.ts' };

const HEADER = '// GENERATED by tools/codegen/copy-shared.mjs from packages/. Do not edit.\n';

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

function rewrite(source, depth) {
  return source.replace(/(from\s+['"])([^'"]+)(['"])/g, (match, open, spec, close) => {
    const target = rewrites[spec];
    if (!target) return match;
    return `${open}${'../'.repeat(depth)}${target}${close}`;
  });
}

const expected = new Map();
for (const { name, dir } of sources) {
  for (const file of walk(dir)) {
    if (!file.endsWith('.ts') || file.endsWith('.test.ts')) continue;
    const rel = relative(dir, file);
    const depth = rel.split('/').length - 1;
    expected.set(join(name, rel), HEADER + rewrite(readFileSync(file, 'utf8'), depth));
  }
}

if (process.argv.includes('--check')) {
  const actual = new Map();
  try {
    for (const file of walk(outDir)) actual.set(relative(outDir, file), readFileSync(file, 'utf8'));
  } catch {
    // Missing directory: every expected file counts as stale below.
  }
  const stale = [
    ...[...expected].filter(([rel, content]) => actual.get(rel) !== content).map(([rel]) => rel),
    ...[...actual.keys()].filter((rel) => !expected.has(rel)),
  ];
  if (stale.length) {
    console.error(`supabase/functions/_shared/generated is stale. Run \`pnpm codegen\`.\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`generated copy is up to date (${expected.size} files)`);
} else {
  rmSync(outDir, { recursive: true, force: true });
  for (const [rel, content] of expected) {
    mkdirSync(dirname(join(outDir, rel)), { recursive: true });
    writeFileSync(join(outDir, rel), content);
  }
  console.log(`wrote ${expected.size} files to ${relative(root, outDir)}`);
}
